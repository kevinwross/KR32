#include <cstdint>
#include <cstdio>
#include <fstream>
#include <iomanip>
#include <iterator>
#include <sstream>
#include <string>
#include <vector>

namespace {

std::uint32_t crc32(const std::vector<std::uint8_t>& data) {
    std::uint32_t crc = 0xFFFF'FFFFU;
    for (const std::uint8_t byte : data) {
        crc ^= byte;
        for (int bit = 0; bit < 8; ++bit) {
            const std::uint32_t mask = 0U - (crc & 1U);
            crc = (crc >> 1U) ^ (0xEDB8'8320U & mask);
        }
    }
    return ~crc;
}

bool read_file(const std::string& path, std::vector<std::uint8_t>& bytes,
               std::string& error) {
    std::ifstream input(path, std::ios::binary);
    if (!input) {
        error = "cannot read " + path;
        return false;
    }
    bytes.assign(std::istreambuf_iterator<char>(input),
                 std::istreambuf_iterator<char>());
    if (!input.good() && !input.eof()) {
        error = "cannot read " + path;
        return false;
    }
    return true;
}

std::string hex_word(std::uint32_t value) {
    std::ostringstream stream;
    stream << std::hex << std::setw(8) << std::setfill('0') << value;
    return stream.str();
}

void write_array(std::ostream& output, const std::string& name,
                 const std::vector<std::uint8_t>& bytes) {
    if (bytes.empty()) {
        output << "constexpr std::array<std::uint8_t, 0> " << name << "{};\n";
        return;
    }
    output << "constexpr std::array<std::uint8_t, " << bytes.size() << "> "
           << name << " = {\n";
    for (std::size_t index = 0; index < bytes.size(); ++index) {
        if (index % 16 == 0) {
            output << "    ";
        }
        output << "0x" << std::hex << std::setw(2) << std::setfill('0')
               << static_cast<unsigned>(bytes[index]) << std::dec;
        if (index + 1 != bytes.size()) {
            output << ", ";
        }
        if (index % 16 == 15 || index + 1 == bytes.size()) {
            output << "\n";
        }
    }
    output << "};\n";
}

} // namespace

int main(int argc, char** argv) {
    std::string bios_path;
    std::string kernel_path;
    std::string output_path;
    bool empty = false;
    for (int index = 1; index < argc; ++index) {
        const std::string argument = argv[index];
        if (argument == "--bios" && index + 1 < argc) {
            bios_path = argv[++index];
        } else if (argument == "--kernel" && index + 1 < argc) {
            kernel_path = argv[++index];
        } else if (argument == "--output" && index + 1 < argc) {
            output_path = argv[++index];
        } else if (argument == "--empty") {
            empty = true;
        } else {
            std::fprintf(stderr, "kr32-embed-os: unknown argument %s\n",
                         argument.c_str());
            return 2;
        }
    }
    if (output_path.empty()) {
        std::fprintf(stderr, "kr32-embed-os: --output is required\n");
        return 2;
    }

    std::vector<std::uint8_t> bios;
    std::vector<std::uint8_t> kernel;
    std::string error;
    if (!empty) {
        if (bios_path.empty() || kernel_path.empty()) {
            std::fprintf(stderr,
                         "kr32-embed-os: --bios and --kernel are required\n");
            return 2;
        }
        if (!read_file(bios_path, bios, error) ||
            !read_file(kernel_path, kernel, error)) {
            std::fprintf(stderr, "kr32-embed-os: %s\n", error.c_str());
            return 1;
        }
    }

    const std::uint32_t bios_crc = crc32(bios);
    const std::uint32_t kernel_crc = crc32(kernel);
    const std::string build_id =
        empty ? std::string("empty")
              : "bios-" + hex_word(bios_crc) + "-kernel-" +
                    hex_word(kernel_crc);
    const std::string bios_span =
        bios.empty()
            ? "std::span<const std::uint8_t>()"
            : "std::span<const std::uint8_t>(kBios.data(), kBios.size())";
    const std::string kernel_span =
        kernel.empty()
            ? "std::span<const std::uint8_t>()"
            : "std::span<const std::uint8_t>(kKernel.data(), kKernel.size())";

    std::ofstream output(output_path, std::ios::binary | std::ios::trunc);
    if (!output) {
        std::fprintf(stderr, "kr32-embed-os: cannot write %s\n",
                     output_path.c_str());
        return 1;
    }
    output << "// Generated by kr32-embed-os; do not edit by hand.\n"
           << "#include \"kr32/os/embedded_os.h\"\n\n"
           << "#include <array>\n"
           << "#include <string_view>\n\n"
           << "namespace kr32::os {\n"
           << "namespace {\n\n";
    write_array(output, "kBios", bios);
    output << "\n";
    write_array(output, "kKernel", kernel);
    output << "\nconstexpr char kBuildId[] = \"" << build_id << "\";\n\n"
           << "} // namespace\n\n"
           << "const EmbeddedOs& embedded_os() {\n"
           << "    static const EmbeddedOs images{\n"
           << "        " << bios_span << ",\n"
           << "        " << kernel_span << ",\n"
           << "        " << bios_crc << "U,\n"
           << "        " << kernel_crc << "U,\n"
           << "        std::string_view(kBuildId)};\n"
           << "    return images;\n"
           << "}\n\n"
           << "bool embedded_os_available() {\n"
           << "    const EmbeddedOs& images = embedded_os();\n"
           << "    return !images.bios.empty() && !images.kernel.empty();\n"
           << "}\n\n"
           << "} // namespace kr32::os\n";
    if (!output) {
        std::fprintf(stderr, "kr32-embed-os: failed writing %s\n",
                     output_path.c_str());
        return 1;
    }
    return 0;
}
